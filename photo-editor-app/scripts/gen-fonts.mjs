// Builds src/styles/fonts.css from @fontsource: only the woff2 files of the subsets we need
// (arabic + latin, one weight per font) so the APK stays small. Run: node scripts/gen-fonts.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

// [package, weight, subsets]. Keep in sync with src/lib/fonts.ts
const FONTS = [
  ['cairo', 700, ['arabic', 'latin']], ['tajawal', 700, ['arabic', 'latin']], ['almarai', 700, ['arabic', 'latin']],
  ['amiri', 700, ['arabic', 'latin']], ['noto-kufi-arabic', 700, ['arabic', 'latin']], ['reem-kufi', 700, ['arabic', 'latin']],
  ['el-messiri', 700, ['arabic', 'latin']], ['changa', 700, ['arabic', 'latin']], ['noto-naskh-arabic', 700, ['arabic', 'latin']],
  ['ibm-plex-sans-arabic', 700, ['arabic', 'latin']], ['vazirmatn', 700, ['arabic', 'latin']], ['markazi-text', 700, ['arabic', 'latin']],
  ['aref-ruqaa', 700, ['arabic', 'latin']], ['lateef', 700, ['arabic', 'latin']], ['lalezar', 400, ['arabic', 'latin']], ['rakkas', 400, ['arabic', 'latin']],
  ['roboto', 700, ['latin']], ['montserrat', 700, ['latin']], ['poppins', 700, ['latin']], ['playfair-display', 700, ['latin']],
  ['oswald', 700, ['latin']], ['inter', 700, ['latin']], ['merriweather', 700, ['latin']],
  ['lobster', 400, ['latin']], ['bebas-neue', 400, ['latin']], ['pacifico', 400, ['latin']], ['anton', 400, ['latin']],
];

const RANGE = {
  arabic: 'U+0600-06FF, U+0750-077F, U+0870-088E, U+0890-0891, U+0897-08E1, U+08E3-08FF, U+200C-200E, U+2010-2011, U+204F, U+2E41, U+FB50-FDFF, U+FE70-FE74, U+FE76-FEFC',
  latin: 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
};
let out = '/* GENERATED by scripts/gen-fonts.mjs - do not edit by hand */\n';
const families = [];
for (const [pkg, weight, subsets] of FONTS) {
  for (const sub of subsets) {
    const css = `node_modules/@fontsource/${pkg}/${sub}-${weight}.css`;
    if (!existsSync(css)) { console.error('missing', css); process.exit(1); }
    let text = readFileSync(css, 'utf8');
    const fam = /font-family:\s*'([^']+)'/.exec(text)?.[1];
    if (!families.includes(fam)) families.push(fam);
    // keep only the woff2 source, point it at node_modules relative to src/styles
    text = text.replace(/src:\s*url\(\.\/files\/([^)]+\.woff2)\)\s*format\('woff2'\)[^;]*;/, (_m, f) =>
      `src: url(../../node_modules/@fontsource/${pkg}/files/${f}) format('woff2');`);
    // the per-subset files have no unicode-range; without it the 2nd @font-face would replace the 1st for every character
    text = text.replace(/\}\s*$/, `  unicode-range: ${RANGE[sub]};\n}`);
    out += text.trim() + '\n';
  }
}
writeFileSync('src/styles/fonts.css', out);
console.log('families:', families.join(' | '));
